import Foundation
typealias P = BloomBoxAccountPolicy
precondition(P.state(available: false, email: .present, token: .present, adsid: .present) == .unavailable)
precondition(P.state(available: true, email: .absent, token: .absent, adsid: .absent) == .notLinked)
precondition(P.state(available: true, email: .present, token: .absent, adsid: .absent) == .incomplete)
precondition(P.state(available: true, email: .present, token: .present, adsid: .present) == .saved)
precondition(P.state(available: true, email: .present, token: .unknown, adsid: .present) == .unknown)
precondition(P.initialAccountPage(.saved) == 3)
precondition(P.initialAccountPage(.unavailable) == 3)
precondition(P.initialAccountPage(.unknown) == 2)
precondition(P.initialAccountPage(.notLinked) == 2)
precondition(P.initialAccountPage(.incomplete) == 2)
let now = Date()
let r = P.request(mode: "signin", now: now)
precondition(Set(r.keys) == Set(["id", "mode", "expires"]))
precondition(UUID(uuidString: r["id"] as! String) != nil)
precondition(r["mode"] as? String == "signin")
precondition((r["expires"] as! Date).timeIntervalSince(now) == 120)
print("PASS: local account presence, optional onboarding and short-lived credential-free entry request.")
